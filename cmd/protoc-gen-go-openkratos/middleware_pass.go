package main

import (
	"fmt"
	"strconv"
	"strings"

	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
)

const (
	middlewarePackage = protogen.GoImportPath("github.com/openkratos/kratos/middleware")
	grpcPackage       = protogen.GoImportPath("google.golang.org/grpc")
)

func generateMiddlewareFile(gen *protogen.Plugin, file *protogen.File, httpEnabled, grpcEnabled, omitHTTP bool) (*protogen.GeneratedFile, error) {
	if len(file.Services) == 0 || !httpEnabled && !grpcEnabled {
		return nil, nil
	}
	applicable := false
	for _, service := range file.Services {
		if grpcEnabled || len(enabledHTTPMethods(service, omitHTTP)) > 0 {
			applicable = true
			break
		}
	}
	if !applicable {
		return nil, nil
	}

	g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+"_openkratos.pb.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-openkratos. DO NOT EDIT.")
	g.P("// versions:")
	g.P(fmt.Sprintf("// - protoc-gen-go-openkratos %s", release))
	g.P("// - protoc                    ", protocVersion(gen))
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()

	for _, service := range file.Services {
		httpMethods := enabledHTTPMethods(service, omitHTTP)
		if !grpcEnabled && len(httpMethods) == 0 {
			continue
		}
		generateMiddlewarePlan(g, service)
		if len(httpMethods) > 0 {
			generateHTTPMiddlewareWrapper(g, service, httpMethods)
		}
		if grpcEnabled {
			generateGRPCMiddlewareWrapper(g, service)
		}
	}
	return g, nil
}

func generateMiddlewarePlan(g *protogen.GeneratedFile, service *protogen.Service) {
	g.P("// ", service.GoName, "Middleware configures generated server middleware for ", service.Desc.FullName(), ".")
	g.P("type ", service.GoName, "Middleware struct {")
	g.P("Unary []", middlewarePackage.Ident("UnaryMiddleware"))
	g.P("Stream []", middlewarePackage.Ident("StreamMiddleware"))
	g.P("Methods ", service.GoName, "MethodMiddleware")
	g.P("}")
	g.P()
	g.P("// ", service.GoName, "MethodMiddleware configures middleware for individual RPC methods.")
	g.P("type ", service.GoName, "MethodMiddleware struct {")
	for _, method := range service.Methods {
		if isStreaming(method) {
			g.P(method.GoName, " []", middlewarePackage.Ident("StreamMiddleware"))
		} else {
			g.P(method.GoName, " []", middlewarePackage.Ident("UnaryMiddleware"))
		}
	}
	g.P("}")
	g.P()
}

func generateHTTPMiddlewareWrapper(g *protogen.GeneratedFile, service *protogen.Service, methods []*protogen.Method) {
	wrapper := lowerFirst(service.GoName) + "HTTPMiddlewareServer"
	g.P("type ", wrapper, " struct {")
	g.P(service.GoName, "HTTPServer")
	for _, method := range methods {
		if isStreaming(method) {
			g.P(lowerFirst(method.GoName), " ", middlewarePackage.Ident("StreamHandler"))
		} else {
			g.P(lowerFirst(method.GoName), " ", middlewarePackage.Ident("UnaryHandler"))
		}
	}
	g.P("}")
	g.P()

	for _, method := range methods {
		if isStreaming(method) {
			generateHTTPStreamAdapters(g, service, method)
		}
	}

	g.P("// Wrap", service.GoName, "HTTPServer snapshots plan and composes every HTTP handler before registration.")
	g.P("func Wrap", service.GoName, "HTTPServer(srv ", service.GoName, "HTTPServer, plan ", service.GoName, "Middleware) (", service.GoName, "HTTPServer, error) {")
	g.P("if srv == nil { return nil, ", fmtPackage.Ident("Errorf"), "(", strconv.Quote("openkratos: nil "+service.GoName+" HTTP server"), ") }")
	g.P("wrapped := &", wrapper, "{", service.GoName, "HTTPServer: srv}")
	for _, method := range methods {
		generateComposeBlock(g, service, method, "HTTP", "srv", "wrapped")
	}
	g.P("return wrapped, nil")
	g.P("}")
	g.P()

	for _, method := range methods {
		generateHTTPWrapperMethod(g, service, method, wrapper)
	}
}

