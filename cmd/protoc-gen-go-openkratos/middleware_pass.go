func generateComposeBlock(g *protogen.GeneratedFile, service *protogen.Service, method *protogen.Method, transport, serviceVar, wrapperVar string) {
	field := lowerFirst(method.GoName)
	qualified := string(service.Desc.FullName()) + "/" + string(method.Desc.Name()) + " " + transport
	g.P("{")
	if isStreaming(method) {
		g.P("middlewares := make([]", middlewarePackage.Ident("StreamMiddleware"), ", 0, len(plan.Stream)+len(plan.Methods.", method.GoName, "))")
		g.P("middlewares = append(middlewares, plan.Stream...)")
		g.P("middlewares = append(middlewares, plan.Methods.", method.GoName, "...)")
		g.P("handler, err := ", middlewarePackage.Ident("ComposeStream"), "(func(request any, stream ", middlewarePackage.Ident("ServerStream"), ") error {")
		generateStreamTerminal(g, service, method, transport, serviceVar)
		g.P("}, middlewares...)")
	} else {
		g.P("middlewares := make([]", middlewarePackage.Ident("UnaryMiddleware"), ", 0, len(plan.Unary)+len(plan.Methods.", method.GoName, "))")
		g.P("middlewares = append(middlewares, plan.Unary...)")
		g.P("middlewares = append(middlewares, plan.Methods.", method.GoName, "...)")
		g.P("handler, err := ", middlewarePackage.Ident("ComposeUnary"), "(func(ctx ", contextPackage.Ident("Context"), ", request any) (any, error) {")
		g.P("typed, ok := request.(*", method.Input.GoIdent, ")")
		g.P("if !ok { return nil, ", fmtPackage.Ident("Errorf"), "(", strconv.Quote("openkratos: "+qualified+" request type %T, want *"+method.Input.GoIdent.GoName), ", request) }")
		g.P("return ", serviceVar, ".", method.GoName, "(ctx, typed)")
		g.P("}, middlewares...)")
	}
	g.P("if err != nil { return nil, ", fmtPackage.Ident("Errorf"), "(", strconv.Quote("openkratos: wrapping "+qualified+": %w"), ", err) }")
	g.P(wrapperVar, ".", field, " = handler")
	g.P("}")
}

func generateStreamTerminal(g *protogen.GeneratedFile, service *protogen.Service, method *protogen.Method, transport, serviceVar string) {
	qualified := string(service.Desc.FullName()) + "/" + string(method.Desc.Name()) + " " + transport
	adapter := streamAdapterName(service, method, transport)
	nativeType := transportHTTPPackage.Ident("ServerStream")
	if transport == "gRPC" {
		nativeType = grpcPackage.Ident("ServerStream")
	}
	g.P("native, ok := stream.Context().Value(", adapter, "Key{}).(", nativeType, ")")
	g.P("if !ok { return ", fmtPackage.Ident("Errorf"), "(", strconv.Quote("openkratos: "+qualified+" lost native stream"), ") }")
	g.P("typedStream := &", adapter, "Typed{ServerStream: native, stream: stream}")
	if method.Desc.IsStreamingClient() {
		g.P("if request != nil { return ", fmtPackage.Ident("Errorf"), "(", strconv.Quote("openkratos: "+qualified+" initial request type %T, want nil"), ", request) }")
		g.P("return ", serviceVar, ".", method.GoName, "(typedStream)")
		return
	}
	g.P("typed, ok := request.(*", method.Input.GoIdent, ")")
	g.P("if !ok { return ", fmtPackage.Ident("Errorf"), "(", strconv.Quote("openkratos: "+qualified+" request type %T, want *"+method.Input.GoIdent.GoName), ", request) }")
	g.P("return ", serviceVar, ".", method.GoName, "(typed, typedStream)")
}

func generateHTTPWrapperMethod(g *protogen.GeneratedFile, service *protogen.Service, method *protogen.Method, wrapper string) {
	field := lowerFirst(method.GoName)
	if !isStreaming(method) {
		g.P("func (s *", wrapper, ") ", method.GoName, "(ctx ", contextPackage.Ident("Context"), ", request *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error) {")
		g.P("reply, err := s.", field, "(ctx, request)")
		g.P("if err != nil { return nil, err }")
		g.P("typed, ok := reply.(*", method.Output.GoIdent, ")")
		g.P("if !ok { return nil, ", fmtPackage.Ident("Errorf"), "(", strconv.Quote("openkratos: "+string(service.Desc.FullName())+"/"+string(method.Desc.Name())+" HTTP reply type %T, want *"+method.Output.GoIdent.GoName), ", reply) }")
		g.P("return typed, nil")
		g.P("}")
		g.P()
		return
	}
	streamType := service.GoName + "_" + method.GoName + "HTTPServer"
	adapter := streamAdapterName(service, method, "HTTP")
	if method.Desc.IsStreamingClient() {
		g.P("func (s *", wrapper, ") ", method.GoName, "(stream ", streamType, ") error {")
		g.P("base := &", adapter, "{ServerStream: stream, ctx: ", contextPackage.Ident("WithValue"), "(stream.Context(), ", adapter, "Key{}, ", transportHTTPPackage.Ident("ServerStream"), "(stream))}")
		g.P("return s.", field, "(nil, base)")
	} else {
		g.P("func (s *", wrapper, ") ", method.GoName, "(request *", method.Input.GoIdent, ", stream ", streamType, ") error {")
		g.P("base := &", adapter, "{ServerStream: stream, ctx: ", contextPackage.Ident("WithValue"), "(stream.Context(), ", adapter, "Key{}, ", transportHTTPPackage.Ident("ServerStream"), "(stream))}")
		g.P("return s.", field, "(request, base)")
	}
	g.P("}")
	g.P()
}

